def validate_premium_emoji_config() -> None:
    """Проверяет только формат ручных ID; количества 83/80 больше не существует."""
    for number, emoji_id in PREMIUM_EMOJI.items():
        try:
            n = int(number)
        except (TypeError, ValueError) as exc:
            raise RuntimeError(f"Premium Emoji: неверный номер позиции {number!r}") from exc
        if n <= 0:
            raise RuntimeError(f"Premium Emoji: номер позиции должен быть > 0: {n}")
        if not str(emoji_id).strip().isdigit():
            raise RuntimeError(f"Premium Emoji №{n}: ID должен состоять только из цифр")


