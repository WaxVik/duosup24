async def main() -> None:
    global bot

    if not BOT_TOKEN:
        raise RuntimeError("BOT_TOKEN не задан в Railway Variables")
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL не задан в Railway Variables")

    validate_premium_emoji_config()
    bot = Bot(
        token=BOT_TOKEN,
        default=DefaultBotProperties(parse_mode=ParseMode.HTML),
    )

    try:
        await init_db()
        me = await bot.get_me()
        global BOT_USERNAME
        BOT_USERNAME = me.username or BOT_USERNAME
        LOGGER.info("DuoSup %s запущен как @%s (id=%s)", BOT_VERSION, BOT_USERNAME, me.id)
        await dp.start_polling(bot)
    finally:
        if db is not None:
            await db.close()
        await bot.session.close()


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )
    asyncio.run(main())
